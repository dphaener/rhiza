// Package docs renders the generated reference under docs/reference from
// plain descriptions of the code. It knows nothing of the api package: the
// caller turns operations into Commands, so the same model always gives the
// same bytes.
package docs

import (
	"fmt"
	"sort"
	"strings"
)

// Param is one argument or flag of a command.
type Param struct {
	// Name is how the parameter reads: "<name>" for an argument, "--name"
	// for a flag.
	Name string
	// Desc is its description, Notes its qualifiers (required, repeatable,
	// one of ...).
	Desc  string
	Notes []string
}

// Field is one field of a command's JSON output.
type Field struct {
	Name string
	Type string
	Desc string
}

// Command is one CLI command.
type Command struct {
	// Name is the command path, such as "change new".
	Name    string
	Summary string
	// Usage is the synopsis line.
	Usage string
	// Writes reports a command that appends to the log.
	Writes bool
	// Input describes a file or stdin document the command reads, if any.
	Input string
	// Params lists the arguments, then the flags.
	Params []Param
	// Output lists the fields of the --json response.
	Output []Field
	// SetsExit reports a command whose result chooses the exit code.
	SetsExit bool
}

// GlobalFlags are the flags every command takes.
var GlobalFlags = []Param{
	{Name: "--json", Desc: "Print JSON instead of markdown"},
	{Name: "--dry-run", Desc: "Build a write and print it; write nothing"},
	{Name: "--change <ref>", Desc: "The change set to act on (env RHIZA_CHANGE)"},
	{Name: "--actor <ref>", Desc: "Who performs the call (env RHIZA_ACTOR)"},
	{Name: "--for <ref>", Desc: "Whom the call acts for (env RHIZA_FOR)"},
	{Name: "--record", Desc: "Write in a record change set landed in one step"},
	{Name: "-h, --help", Desc: "Show this help, or describe a command"},
}

// ExitCodes are the exit codes every command shares.
var ExitCodes = []Field{
	{Name: "0", Desc: "Success"},
	{Name: "1", Desc: "Any other error"},
	{Name: "2", Desc: "Usage error: unknown command or flag, a missing or bad argument"},
	{Name: "3", Desc: "Conflict: the state changed or does not allow the call"},
	{Name: "4", Desc: "Not found: the named node, change set, run or operation does not exist"},
}

// CLI renders cli.md: every command with its arguments, flags, output and
// exit codes. Commands are sorted by name.
func CLI(cmds []Command) []byte {
	cmds = append([]Command(nil), cmds...)
	sort.Slice(cmds, func(i, j int) bool { return cmds[i].Name < cmds[j].Name })
	var b strings.Builder
	b.WriteString("# CLI reference\n\n")
	b.WriteString("<!-- Generated by `rhiza docs` from the command registry. Do not edit. -->\n\n")
	b.WriteString("Every command takes the global flags, prints markdown or, with `--json`, JSON, and exits with one of the codes below.\n\n")
	b.WriteString("## Global flags\n\n")
	writeParams(&b, GlobalFlags)
	b.WriteString("\n## Exit codes\n\n")
	for _, e := range ExitCodes {
		fmt.Fprintf(&b, "- `%s`: %s\n", e.Name, e.Desc)
	}
	b.WriteString("\n## Commands\n\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "- [`rhiza %s`](#%s)\n", c.Name, anchor(c.Name))
	}
	for _, c := range cmds {
		fmt.Fprintf(&b, "\n## rhiza %s\n\n%s.\n\n```\n%s\n```\n", c.Name, strings.TrimSuffix(c.Summary, "."), c.Usage)
		if c.Writes {
			b.WriteString("\nAppends to the log.\n")
		}
		if c.Input != "" {
			fmt.Fprintf(&b, "\nInput: %s. Its schema: `rhiza describe %s --json`.\n", c.Input, strings.ReplaceAll(c.Name, " ", "."))
		}
		if len(c.Params) > 0 {
			b.WriteString("\nArguments and flags:\n\n")
			writeParams(&b, c.Params)
		}
		if len(c.Output) > 0 {
			b.WriteString("\nOutput (`--json` fields):\n\n")
			for _, f := range c.Output {
				fmt.Fprintf(&b, "- `%s` (%s): %s\n", f.Name, f.Type, f.Desc)
			}
		}
		if c.SetsExit {
			b.WriteString("\nExit code: set by the result, besides the shared codes.\n")
		}
	}
	return []byte(b.String())
}

func writeParams(b *strings.Builder, ps []Param) {
	for _, p := range ps {
		line := "- `" + p.Name + "`"
		if p.Desc != "" {
			line += ": " + p.Desc
		}
		if len(p.Notes) > 0 {
			line += " (" + strings.Join(p.Notes, "; ") + ")"
		}
		b.WriteString(line + "\n")
	}
}

// anchor is the GitHub heading anchor for "rhiza <name>".
func anchor(name string) string {
	a := strings.ToLower("rhiza " + name)
	var b strings.Builder
	for _, r := range a {
		switch {
		case r == ' ' || r == '-':
			b.WriteRune('-')
		case r == '_' || r >= 'a' && r <= 'z' || r >= '0' && r <= '9':
			b.WriteRune(r)
		}
	}
	return b.String()
}

// Setting is one rhiza.toml (or project git config) setting.
type Setting struct {
	Key     string
	Type    string
	Default string
	Scope   string
	Desc    string
	// Flag is the daemon flag that overrides the setting, if any.
	Flag string
}

// Config renders config.md: every setting with its type, default and
// description, machine settings first, each group in the order given.
func Config(settings []Setting) []byte {
	var b strings.Builder
	b.WriteString("# Settings reference\n\n")
	b.WriteString("<!-- Generated by `rhiza docs` from the settings definitions. Do not edit. -->\n\n")
	b.WriteString("Machine settings live in the root's `rhiza.toml`; project settings live in the project's git config. Read them with `rhiza daemon settings` and write one with `rhiza daemon set`.\n")
	for _, scope := range []string{"machine", "project"} {
		fmt.Fprintf(&b, "\n## %s settings\n\n", strings.ToUpper(scope[:1])+scope[1:])
		for _, s := range settings {
			if s.Scope != scope {
				continue
			}
			def := "unset"
			if s.Default != "" {
				def = "`" + s.Default + "`"
			}
			fmt.Fprintf(&b, "### `%s`\n\n%s.\n\n- Type: %s\n- Default: %s\n", s.Key, strings.TrimSuffix(s.Desc, "."), s.Type, def)
			if s.Flag != "" {
				fmt.Fprintf(&b, "- Flag: `rhiza daemon %s` overrides it for a run\n", s.Flag)
			}
			b.WriteString("\n")
		}
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}
